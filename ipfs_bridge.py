#!/usr/bin/env python3
"""
Bridge: Lean Node Export -> IPFS DAG-CBOR
Fetches all sections from the Lean node, encodes them as DAG-CBOR,
and outputs the IPFS commands needed to publish them.
"""
import json
import urllib.request
import sys

try:
    import cbor2
except ImportError:
    print("Please install cbor2: sudo apt install python3-cbor2")
    sys.exit(1)

BASE = "http://127.0.0.1:8080"

def fetch_export():
    with urllib.request.urlopen(f"{BASE}/api/erdfa/export", timeout=5) as r:
        return json.loads(r.read())

def to_dag_cbor(sections):
    # In a real IPLD DAG, we would construct a Merkle DAG.
    # Here we encode the entire array as a single CBOR block for simplicity.
    # The standard IPFS CIDv1 for DAG-CBOR will be generated by ipfs dag put.
    return cbor2.dumps(sections)

if __name__ == "__main__":
    print("=== Lean Node -> IPFS Bridge ===")
    sections = fetch_export()
    print(f"Fetched {len(sections)} sections from Lean node.")
    
    cbor_data = to_dag_cbor(sections)
    output_file = "lean_export.cbor"
    
    with open(output_file, "wb") as f:
        f.write(cbor_data)
    
    print(f"Encoded to DAG-CBOR: {output_file} ({len(cbor_data)} bytes)")
    print("\nTo publish to IPFS, run:")
    print(f"  ipfs dag put --store-codec dag-cbor --input-codec dag-cbor {output_file}")
    print("\nThis will return a CID (Content Identifier) that you can use in your IPFS pipeline.")
